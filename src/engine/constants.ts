/**
 * Registry Helper Functions
 */
export function getConstant<T = number>(id: string): T {
  const entry = CONSTANTS_REGISTRY[id];
  if (!entry) {
    throw new Error(`Constant with id '${id}' not found in registry.`);
  }
  return entry.value as T;
}

export function getConstantEntry(id: string): ConstantEntry<any> {
  const entry = CONSTANTS_REGISTRY[id];
  if (!entry) {
    throw new Error(`Constant with id '${id}' not found in registry.`);
  }
  return entry;
}

export function getConstantsByCategory(category: ConstantCategory): ConstantEntry<any>[] {
  return Object.values(CONSTANTS_REGISTRY).filter((c) => c.category === category);
}

export function getConstantsByTier(tier: ParameterTier): ConstantEntry<any>[] {
  return Object.values(CONSTANTS_REGISTRY).filter((c) => c.tier === tier);
}
